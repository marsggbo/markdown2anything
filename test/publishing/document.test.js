'use strict';
const assert = require('assert');
const { parseSavedDocument, renderAssetMarkers } = require('../../lib/publishing/document');
const parsed = parseSavedDocument('# Title\n\n![A](a.png "caption A")\n\n<figure><img src="b.png" alt="B"><figcaption>caption B</figcaption></figure>\n\n![C](c.png)\n\n`![no](code.png)`\n\n<!-- <img src="comment.png"> -->', { documentPath: '/tmp/post.md' });
assert.deepStrictEqual(parsed.assets.map(asset => asset.assetId), ['asset-0000', 'asset-0001', 'asset-0002']);
assert.deepStrictEqual(parsed.assets.map(asset => asset.alt), ['A', 'B', 'C']);
assert.strictEqual(parsed.assets[1].caption, 'caption B');
assert.ok(renderAssetMarkers(parsed.article).includes('asset-0001'));
assert.throws(() => parseSavedDocument('<video src="outside.mp4"></video>', { documentPath: '/tmp/post.md' }), /UNSAFE_RAW_HTML/);
assert.throws(() => parseSavedDocument('<img src="a.png" srcset="b.png 2x">', { documentPath: '/tmp/post.md' }), /UNMODELED_IMAGE_SOURCE/);
console.log('✓ publishing document');

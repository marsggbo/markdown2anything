'use strict';
const assert = require('assert');
const { loadBundledProfiles, validateProfile, profileAvailability } = require('../../lib/publishing/profiles');
const profiles = loadBundledProfiles();
const wechat = profiles.find(item => item.profile.id === 'wechat-official-core');
const zhihuOfficial = profiles.find(item => item.profile.id === 'zhihu-official-article-v1');
const zhihuBrowser = profiles.find(item => item.profile.id === 'zhihu-browser-write-v1');
const cnblogs = profiles.find(item => item.profile.id === 'cnblogs-metaweblog-v1');
assert.ok(wechat.validation.valid); assert.deepStrictEqual(profileAvailability(wechat.profile).supportedOptions, ['comments']);
assert.ok(zhihuOfficial.validation.valid); assert.deepStrictEqual(profileAvailability(zhihuOfficial.profile).supportedOptions, ['commentPermission', 'creationDeclaration', 'tableOfContents', 'topics']);
assert.deepStrictEqual(profileAvailability(zhihuBrowser.profile).supportedOptions, []);
assert.strictEqual(profileAvailability(cnblogs.profile).availability, 'unavailable'); assert.strictEqual(profileAvailability(cnblogs.profile).reason, 'NO_REVIEWABLE_PREPARE_PATH');
const incomplete = JSON.parse(JSON.stringify(wechat.profile)); delete incomplete.routes.accessToken.timeoutMs; assert.ok(!validateProfile(incomplete).valid);
console.log('✓ publishing profiles');
